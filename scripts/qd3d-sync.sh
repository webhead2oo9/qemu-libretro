# Copy the QD3D wire contract and host executor from an XPDriver checkout
# into hw/qd3d. hw/qd3d/proto and hw/qd3d/host are generated copies: change
# them in XPDriver (qd3d/) and re-run this script, never edit them here.
#
# usage: scripts/qd3d-sync.sh <XPDriver checkout>
set -eu

src=${1:?usage: scripts/qd3d-sync.sh <XPDriver checkout>}
dst=$(cd "$(dirname "$0")/../hw/qd3d" && pwd)

[ -f "$src/qd3d/proto/qd3d_proto.h" ] || {
    echo "qd3d-sync: $src is not an XPDriver checkout" >&2
    exit 1
}

rm -rf "$dst/proto" "$dst/host"
mkdir -p "$dst/proto" "$dst/host"
cp "$src"/qd3d/proto/*.h "$dst/proto/"
# Executor library sources only: no harness, no self-tests.
for f in "$src"/qd3d/host/*.c "$src"/qd3d/host/*.h; do
    case $(basename "$f") in
    *selftest*|*loopback*) continue ;;
    esac
    cp "$f" "$dst/host/"
done
git -C "$src" rev-parse HEAD > "$dst/SYNCED_FROM" 2>/dev/null || true
{
    echo "# Generated by scripts/qd3d-sync.sh; do not edit."
    echo "qd3d_host_ss = files("
    for f in "$dst"/host/*.c; do
        echo "  '$(basename "$f")',"
    done
    echo ")"
} > "$dst/host/meson.build"
echo "qd3d-sync: copied $(ls "$dst/proto" "$dst/host" | grep -c '\.[ch]$') files"
